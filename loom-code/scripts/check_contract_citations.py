def find_repo_root(start: Path) -> Path:
    """Walk up from `start` to the nearest `.git` dir; else cwd."""
    current = start.resolve()
    for parent in (current, *current.parents):
        if (parent / ".git").exists():
            return parent
    return Path.cwd()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Check that every runtime prose contract under the scope "
            "cites only files that ship with it, against a shrink-only "
            "debt list of today's known violators."
        )
    )
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=None,
        help="repo root to scan (default: nearest .git ancestor of this script)",
    )
    args = parser.parse_args(argv)

    repo_root = args.repo_root or find_repo_root(Path(__file__).parent)
    actual = scan_repo(repo_root)
    ok, messages = evaluate(set(actual.keys()), DEBT_LIST)

    if not ok:
        for message in messages:
            print(message, file=sys.stderr)
        # New violations carry their offending citations for the fixer.
        for rel_path in sorted(set(actual) - DEBT_LIST):
            for cand in actual[rel_path]:
                print(f"    {rel_path}: {cand}", file=sys.stderr)
        return 1

    print(
        f"OK: {len(DEBT_LIST)} known-violating files unchanged, "
        "no new contract citations of this repo's records."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
